-- Pedidos de la tienda.
-- Nadie inserta directo en las tablas: los pedidos se crean solo con create_order(),
-- que toma los precios ACTUALES de la base e ignora cualquier precio enviado por el navegador.

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid null references auth.users (id) on delete set null,
  customer_name text not null,
  email text not null,
  phone text not null,
  city text not null,
  address text not null,
  notes text,
  total numeric(12, 2) not null check (total >= 0),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipped', 'cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists orders_user_idx on public.orders (user_id);
create index if not exists orders_status_created_idx on public.orders (status, created_at desc);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  product_id bigint references public.productos (id) on delete set null,
  product_name text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity int not null check (quantity between 1 and 10)
);

create index if not exists order_items_order_idx on public.order_items (order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- orders: cada usuario lee los suyos; el admin lee y actualiza todos. Sin políticas de INSERT/DELETE.
drop policy if exists "Usuarios leen sus pedidos" on public.orders;
create policy "Usuarios leen sus pedidos"
  on public.orders for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "Admin lee todos los pedidos" on public.orders;
create policy "Admin lee todos los pedidos"
  on public.orders for select
  using (public.get_current_user_role() = 'admin');

drop policy if exists "Admin actualiza pedidos" on public.orders;
create policy "Admin actualiza pedidos"
  on public.orders for update
  using (public.get_current_user_role() = 'admin')
  with check (public.get_current_user_role() = 'admin');

-- order_items: visibles si el pedido es visible para el usuario.
drop policy if exists "Usuarios leen items de sus pedidos" on public.order_items;
create policy "Usuarios leen items de sus pedidos"
  on public.order_items for select
  to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

drop policy if exists "Admin lee todos los items" on public.order_items;
create policy "Admin lee todos los items"
  on public.order_items for select
  using (public.get_current_user_role() = 'admin');

-- El admin solo puede cambiar el estado del pedido, no los datos del cliente ni el total.
revoke update on public.orders from anon, authenticated;
grant update (status) on public.orders to authenticated;

create or replace function public.create_order(payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := nullif(trim(payload ->> 'customer_name'), '');
  v_email text := lower(nullif(trim(payload ->> 'email'), ''));
  v_phone text := regexp_replace(coalesce(payload ->> 'phone', ''), '\D', '', 'g');
  v_city text := nullif(trim(payload ->> 'city'), '');
  v_address text := nullif(trim(payload ->> 'address'), '');
  v_notes text := nullif(left(trim(coalesce(payload ->> 'notes', '')), 1000), '');
  v_order_id bigint;
  v_lines jsonb;
  v_total numeric(12, 2);
  v_requested int;
  v_found int;
begin
  if v_name is null or length(v_name) < 2 then
    raise exception 'Escribe tu nombre completo.' using errcode = '22023';
  end if;
  if v_email is null or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'El correo electrónico no es válido.' using errcode = '22023';
  end if;
  if v_phone !~ '^\d{10}$' then
    raise exception 'El teléfono debe tener 10 dígitos.' using errcode = '22023';
  end if;
  if v_city is null then
    raise exception 'Escribe tu ciudad.' using errcode = '22023';
  end if;
  if v_address is null or length(v_address) < 5 then
    raise exception 'Escribe la dirección de entrega.' using errcode = '22023';
  end if;

  -- Ítems pedidos: se agrupan por producto y la cantidad queda entre 1 y 10.
  -- Solo se lee product_id y quantity; cualquier precio enviado por el navegador se ignora.
  select coalesce(jsonb_agg(jsonb_build_object('product_id', product_id, 'quantity', quantity)), '[]'::jsonb)
    into v_lines
    from (
      select (item ->> 'product_id')::bigint as product_id,
             least(10, greatest(1, sum(
               case when (item ->> 'quantity') ~ '^\d{1,3}$' then (item ->> 'quantity')::int else 1 end
             )))::int as quantity
        from jsonb_array_elements(
               case when jsonb_typeof(payload -> 'items') = 'array' then payload -> 'items' else '[]'::jsonb end
             ) as item
       where (item ->> 'product_id') ~ '^\d{1,18}$'
       group by 1
    ) grouped;

  select count(*), count(p.id), sum(coalesce(p.precio_promocional, p.precio) * l.quantity)
    into v_requested, v_found, v_total
    from jsonb_to_recordset(v_lines) as l(product_id bigint, quantity int)
    left join productos p on p.id = l.product_id;

  if v_requested = 0 then
    raise exception 'El carrito está vacío.' using errcode = '22023';
  end if;
  if v_requested > 50 then
    raise exception 'El pedido tiene demasiados productos distintos.' using errcode = '22023';
  end if;
  if v_found <> v_requested then
    raise exception 'Algún producto de tu carrito ya no está disponible. Revisa el carrito e inténtalo de nuevo.'
      using errcode = 'P0002';
  end if;

  insert into orders (user_id, customer_name, email, phone, city, address, notes, total)
  values (auth.uid(), v_name, v_email, v_phone, v_city, v_address, v_notes, v_total)
  returning id into v_order_id;

  insert into order_items (order_id, product_id, product_name, unit_price, quantity)
    select v_order_id, p.id, p.nombre, coalesce(p.precio_promocional, p.precio), l.quantity
      from jsonb_to_recordset(v_lines) as l(product_id bigint, quantity int)
      join productos p on p.id = l.product_id;

  return v_order_id;
end;
$$;

revoke all on function public.create_order(jsonb) from public;
grant execute on function public.create_order(jsonb) to anon, authenticated;
