-- Esquema base del catálogo.
-- Columnas deducidas de src/insert_data.sql (ahora supabase/seed.sql) y de los hooks de administración.

create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  nombre text not null unique
);

create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  precio numeric(12, 2) not null check (precio > 0),
  precio_promocional numeric(12, 2) check (precio_promocional is null or precio_promocional > 0),
  descripcion text not null,
  personaje text,
  tipo_lana text,
  aguja text,
  dificultad text,
  tamano text,
  tiempo_estimado text,
  detalles text,
  created_at timestamptz not null default now(),
  constraint productos_promocion_menor_al_precio
    check (precio_promocional is null or precio_promocional < precio)
);

create table if not exists public.producto_categorias (
  producto_id bigint not null references public.productos (id) on delete cascade,
  categoria_id bigint not null references public.categorias (id) on delete cascade,
  primary key (producto_id, categoria_id)
);

create index if not exists producto_categorias_categoria_idx
  on public.producto_categorias (categoria_id);

create table if not exists public.imagenes (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos (id) on delete cascade,
  url text not null check (length(trim(url)) > 0)
);

create index if not exists imagenes_producto_idx on public.imagenes (producto_id);
